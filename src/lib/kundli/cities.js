export const TZ_OPTIONS = Array.from({ length: 55 }, (_, i) => -12 + i * 0.5);

export function formatTz(tz) {
  const sign = tz < 0 ? "-" : "+";
  const abs = Math.abs(tz);
  const h = Math.floor(abs);
  const m = Math.round((abs - h) * 60);
  return `UTC${sign}${h}${m ? `:${String(m).padStart(2, "0")}` : ":00"}`;
}