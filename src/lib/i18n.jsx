const DICT = { en: EN, hi: HI };

const LanguageContext = createContext(null);

const fallback = { lang: "en", setLang: () => {}, t: (k) => EN[k] ?? k, tf: (k, v) => EN[k] ?? k };

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(KEY);
      if (saved === "hi" || saved === "en") setLangState(saved);
    } catch {
      /* storage blocked — stay on English */
    }
  }, []);

  // Drives the Devanagari font + no-tracking rules in index.css.
  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const value = useMemo(() => {
    const setLang = (next) => {
      setLangState(next);
      try {
        localStorage.setItem(KEY, next);
      } catch {
        /* ignore */
      }
    };
    const t = (key) => DICT[lang][key] ?? EN[key] ?? key;
    const tf = (key, vars) =>
      Object.entries(vars || {}).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v ?? ""), t(key));
    return { lang, setLang, t, tf };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  return useContext(LanguageContext) ?? fallback;
}